-- Game definitions. Does not reset or replace player/account data.
CREATE TABLE IF NOT EXISTS ItemDefinition (
 ItemID INT PRIMARY KEY, ItemKey VARCHAR(64) NOT NULL UNIQUE, Name VARCHAR(128) NOT NULL,
 Kind INT NOT NULL, EquipmentSlot INT NOT NULL, Power INT NOT NULL, Heal FLOAT NOT NULL,
 GatherEventKey INT NOT NULL, CraftEventKey INT NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS SkillDefinition (
 SkillID INT PRIMARY KEY, Name VARCHAR(128) NOT NULL, Duration FLOAT NOT NULL, ImpactSeconds FLOAT NOT NULL,
 Reach FLOAT NOT NULL, Damage FLOAT NOT NULL, Cooldown FLOAT NOT NULL, Knockback FLOAT NOT NULL,
 DamageRatio FLOAT NOT NULL, AreaRadius FLOAT NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS Recipe (
 RecipeID INT PRIMARY KEY, CraftSeconds FLOAT NOT NULL, ResultItemID INT NOT NULL, ResultCount INT NOT NULL,
 FOREIGN KEY(ResultItemID) REFERENCES ItemDefinition(ItemID)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS RecipeIngredient (
 RecipeID INT NOT NULL, IngredientIndex INT NOT NULL, ItemID INT NOT NULL, RequiredCount INT NOT NULL,
 PRIMARY KEY(RecipeID,IngredientIndex), FOREIGN KEY(RecipeID) REFERENCES Recipe(RecipeID),
 FOREIGN KEY(ItemID) REFERENCES ItemDefinition(ItemID)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS QuestDefinition (
 QuestID INT PRIMARY KEY, Name VARCHAR(128) NOT NULL, Description TEXT NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS QuestCondition (
 QuestID INT NOT NULL, ConditionIndex INT NOT NULL, EventKind INT NOT NULL, TargetID INT NOT NULL, RequiredCount INT NOT NULL,
 PRIMARY KEY(QuestID,ConditionIndex), FOREIGN KEY(QuestID) REFERENCES QuestDefinition(QuestID)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS QuestReward (
 QuestID INT NOT NULL, RewardIndex INT NOT NULL, ItemID INT NOT NULL, Amount INT NOT NULL,
 PRIMARY KEY(QuestID,RewardIndex), FOREIGN KEY(QuestID) REFERENCES QuestDefinition(QuestID),
 FOREIGN KEY(ItemID) REFERENCES ItemDefinition(ItemID)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS TutorialDefinition (
 StepID INT PRIMARY KEY, NextStepID INT NOT NULL, EventKind INT NOT NULL, TargetID INT NOT NULL DEFAULT -1,
 MinimumSeconds FLOAT NOT NULL, TargetX FLOAT NOT NULL, TargetY FLOAT NOT NULL, TargetZ FLOAT NOT NULL,
 TargetRadius FLOAT NOT NULL, AllowMove BOOLEAN NOT NULL, AllowAttack BOOLEAN NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS GameSetting (SettingKey VARCHAR(64) PRIMARY KEY, IntValue INT NOT NULL) ENGINE=InnoDB;
